import os
import random

import streamlit as st

from faker_db import FakerDb

BATCH_SIZE = 10
db = FakerDb(os.environ["DATABASE_URL"])
users = st.cache_data(db.users)
locales = st.cache_data(db.locales)


def first_batch():
    st.session_state.batch = 0


def random_seed():
    st.session_state.seed = random.randint(0, 999_999)
    first_batch()


def move(step: int):
    st.session_state.batch += step


st.set_page_config("Faker SQL", layout="wide")
st.title("Faker SQL")
st.caption("Fake people, generated by PostgreSQL stored procedures.")
st.session_state.setdefault("batch", 0)
st.session_state.setdefault("seed", random.randint(0, 999_999))

names = locales()
left, middle, right = st.columns([2, 2, 1], vertical_alignment="bottom")
locale = left.radio("Region", names, format_func=lambda c: f"{names[c]} ({c})", horizontal=True, on_change=first_batch)
seed = middle.number_input("Seed", min_value=0, max_value=2**53 - 1, step=1, key="seed", on_change=first_batch)
right.button("Random seed", on_click=random_seed)

batch = st.session_state.batch
st.subheader(f"Batch {batch + 1}: people {batch * BATCH_SIZE + 1} to {(batch + 1) * BATCH_SIZE}")
st.dataframe(users(locale, seed, batch, BATCH_SIZE), hide_index=True)
previous, following, _ = st.columns([1, 1, 6])
previous.button("Previous batch", on_click=move, args=(-1,), disabled=batch == 0)
following.button("Next batch", on_click=move, args=(1,), type="primary")
